    ap.add_argument('--owner', nargs='*', default=[], help='著作权人名称或代码前缀（版权行含此名称时不算第三方）')
    ap.add_argument('--allow', nargs='*', default=[], help='强制收录的文件')
    ap.add_argument('--json')
    ap.add_argument('--name'); ap.add_argument('--version', default='V1.0')
    ap.add_argument('-o', '--out')
    ap.add_argument('--files-from', help='每行一个文件路径，按此顺序排列（覆盖自动排序与选择）')
    ap.add_argument('--first'); ap.add_argument('--last')
    ap.add_argument('--lines-per-page', type=int, default=50)
    ap.add_argument('--keep-blank', action='store_true')
    ap.add_argument('--scrub', action='store_true')
    ap.add_argument('--line-numbers', choices=['page', 'continuous', 'none'], default='page')
    ap.add_argument('--font', default='宋体', help='中文字体，默认宋体')
    ap.add_argument('--ascii-font', default='Courier New', help='英文与数字字体，默认等宽的 Courier New，保证折行计算准确')
    ap.add_argument('--size', type=float, default=10.0, help='字号（磅），默认 10')
    ap.add_argument('--pdf', action='store_true')
    a = ap.parse_args()

    if a.files_from:
        files = [l.strip() for l in open(a.files_from, encoding='utf-8') if l.strip() and not l.startswith('#')]
        third = []
    else:
        files, third = collect(a.paths, a.exclude, a.owner, a.allow)
    if not files:
        raise SystemExit('ERROR 没有找到可收录的源代码文件')
    st = [file_stats(p) for p in files]
    tot = {k: sum(s[k] for s in st) for k in ('lines', 'blank', 'comment')}
    tot['files'] = len(st)
    tot['nonblank'] = tot['lines'] - tot['blank']
    tot['blank_comment_ratio'] = round((tot['blank'] + tot['comment']) / max(tot['lines'], 1), 3)
    print('收录 %d 个文件，共 %d 行（非空 %d 行，注释约 %d 行，空行 %d 行，注释+空行占比 %.1f%%）'
          % (tot['files'], tot['lines'], tot['nonblank'], tot['comment'], tot['blank'], tot['blank_comment_ratio'] * 100))
    if third:
        print('排除第三方/自动生成文件 %d 个（如属自研，用 --owner 或 --allow 收录）：' % len(third))
        for p, why in third[:40]:
            print('   -', p, '|', why)
        if len(third) > 40:
            print('   … 另有 %d 个' % (len(third) - 40))
    report = dict(totals=tot, files=st, third_party_excluded=[dict(path=p, reason=w) for p, w in third])

    if a.cmd == 'stats':
        if a.json:
            json.dump(report, open(a.json, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        return

    if not (a.name and a.out):
        raise SystemExit('ERROR build 需要 --name 和 -o')
    if not a.files_from:
        files = order_files(files, a.first, a.last)
    page_w, page_h = 11906, 16838
    mar = dict(top=1440, bottom=1440, left=1440, right=1440)
    text_w_pt = (page_w - mar['left'] - mar['right']) / 20
    mono = a.ascii_font.lower() in ('courier new', 'courier', 'consolas', 'menlo', 'monaco', 'liberation mono', 'dejavu sans mono')
    width = int(text_w_pt / (a.size * (0.6 if mono else 0.62))) - 2   # 等宽字体每字符 0.6em；非等宽按 0.62em 保守估计
    text_h = page_h - mar['top'] - mar['bottom']
    line_tw = min(300, text_h // (a.lines_per_page + 1))
    lines, flagged, removed, src_map = prepare_lines(files, a.keep_blank, a.scrub, width)
    lpp = a.lines_per_page
    pages_all = math.ceil(len(lines) / lpp)
    if pages_all > 60:
        sel = lines[:30 * lpp] + lines[-30 * lpp:]
        mode = '前30页 + 后30页（全部 %d 页）' % pages_all
    else:
        sel = lines
        mode = '全部 %d 页（不足 60 页，整体提交）' % pages_all
    build_docx(a.out, sel, a.name, a.version, a.font, a.ascii_font, a.size, line_tw, lpp, a.line_numbers, page_w, page_h, mar)
    first = next((l for l in sel if l.strip()), '')
    last = next((l for l in reversed(sel) if l.strip()), '')
    print('生成 %s：%s，每页 %d 行，折行宽度 %d 列' % (a.out, mode, lpp, width))
    print('首行：%s\n末行：%s' % (first.strip()[:80], last.strip()[:80]))
    lang0 = CODE_EXT[os.path.splitext(files[0])[1].lower()]
    if lang0 in FIRST_OK and not FIRST_OK[lang0].search(first):
        print('WARN 首行不是常见的文件开头（#include / import 等），考虑用 --first 指定入口文件')
    if CODE_EXT[os.path.splitext(files[-1])[1].lower()] == 'c' and not last.strip().endswith('}'):
        print('WARN 末行不以 } 结尾，考虑用 --last 指定以完整函数结尾的文件')
    if flagged:
        print('WARN 收录代码中有 %d 行含网址/邮箱/版权/公司名字样（见报告）；整行注释可用 --scrub 删除，代码行请人工处理' % len(flagged))
    if removed:
        print('已按 --scrub 删除 %d 行注释（见报告）' % len(removed))
    if tot['blank_comment_ratio'] > 0.30:
        print('WARN 注释+空行占比超过 30%%（%.1f%%）' % (tot['blank_comment_ratio'] * 100))
    report.update(order=files, line_map=[dict(path=p, first_line=s, last_line=e) for p, s, e in src_map],
                  submitted=dict(mode=mode, pages=math.ceil(len(sel) / lpp), lines_per_page=lpp,
                                 first_line=first, last_line=last),
                  flagged_lines=flagged, scrubbed_lines=removed)
    if a.pdf:
        pdf, counts = verify_pdf(a.out, lpp, a.name)
        short = [i + 1 for i, c in enumerate(counts[:-1]) if c < lpp]
        print('PDF 核对：%d 页，每页行数 %d~%d；%s' % (len(counts), min(counts), max(counts),
              '除末页外每页均不少于 %d 行' % lpp if not short else 'WARN 行数不足的页：%s' % short))
        report['pdf_check'] = dict(pdf=pdf, line_counts=counts, short_pages=short)
    rp = os.path.splitext(a.out)[0] + '_报告.json'
    json.dump(report, open(rp, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('报告：', rp)


