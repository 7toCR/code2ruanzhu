def read_text(p):
    raw = open(p, 'rb').read()
    for enc in ('utf-8-sig', 'gb18030', 'latin-1'):
        try:
            return raw.decode(enc), enc
        except UnicodeDecodeError:
            continue
    return raw.decode('utf-8', 'replace'), 'utf-8?'


def is_comment_line(line, lang, in_block):
    """返回 (是否注释行, 新的块注释状态)。启发式，只用于统计。"""
    s = line.strip()
    if lang in ('c', 'asm'):
        if in_block:
            return True, '*/' not in s
        if s.startswith('//') or (lang == 'asm' and (s.startswith(';') or s.startswith('@'))):
            return True, False
        if s.startswith('/*'):
            return True, '*/' not in s[2:]
        return False, False
    if lang == 'hash':
        return s.startswith('#') and not s.startswith('#!'), False
    if lang == 'dash':
        return s.startswith('--'), False
    if lang == 'html':
        if in_block:
            return True, '-->' not in s
        if s.startswith('<!--'):
            return True, '-->' not in s
        return False, False
    return False, False


def collect(roots, extra_excludes, owners, allow):
    files, third = [], []
    excl = {e.lower() for e in EXCLUDE_DIRS}
    pats = [e for e in extra_excludes]
    for root in roots:
        cands = []
        if os.path.isfile(root):
            cands = [root]
        else:
            for dp, dns, fns in os.walk(root):
                dns[:] = sorted(d for d in dns if d.lower() not in excl and not d.lower().startswith('cmake-build')
                                and not any(fnmatch.fnmatch(os.path.join(dp, d), p) or fnmatch.fnmatch(d, p) for p in pats))
                for f in sorted(fns):
                    cands.append(os.path.join(dp, f))
        for p in cands:
            ext = os.path.splitext(p)[1].lower()
            name = os.path.basename(p)
            if ext not in CODE_EXT or any(fnmatch.fnmatch(name, x) for x in EXCLUDE_FILES):
                continue
            if any(fnmatch.fnmatch(p, x) or fnmatch.fnmatch(name, x) for x in pats):
                continue
            head = '\n'.join(read_text(p)[0].splitlines()[:60])
            forced = any(os.path.abspath(p) == os.path.abspath(a) or name == a for a in allow)
            hit = THIRD_PARTY.search(head)
            cr = [l for l in head.splitlines() if COPYRIGHT.search(l)]
            own = any(o and o.lower() in l.lower() for l in cr for o in owners)
            if not forced and (hit or (cr and not own)):
                third.append((p, (hit.group(0) if hit else cr[0].strip())[:80]))
                continue
            files.append(p)
    # 去重保持顺序
    seen, uniq = set(), []
    for p in files:
        a = os.path.abspath(p)
        if a not in seen:
            seen.add(a); uniq.append(p)
    return uniq, third


def file_stats(p):
    text, enc = read_text(p)
    lang = CODE_EXT[os.path.splitext(p)[1].lower()]
    total = blank = comment = 0
    blk = False
    for line in text.splitlines():
        total += 1
        if not line.strip():
            blank += 1
            continue
        c, blk = is_comment_line(line, lang, blk)
        comment += c
    return dict(path=p, lang=lang, enc=enc, lines=total, blank=blank, comment=comment)


def order_files(files, first, last):
    def key(p):
        d, n = os.path.split(p)
        ext = os.path.splitext(n)[1].lower()
        return (1 if ext in ('.h', '.hpp', '.hh') else 0, d.lower(), n.lower())   # 先源文件后头文件
    rest = sorted(files, key=key)
    head = []
    if first:
        head = [p for p in rest if p.endswith(first) or os.path.basename(p) == first][:1]
    else:
        for pat in ENTRY:
            hit = [p for p in rest if re.search(pat, os.path.basename(p), re.I)]
            if hit:
                head = hit[:1]
                break
    rest = [p for p in rest if p not in head]
    tail = []
    if last:
        tail = [p for p in rest if p.endswith(last) or os.path.basename(p) == last][:1]
    else:
        def ends_brace(p):
            ls = [l for l in read_text(p)[0].splitlines() if l.strip()]
            return bool(ls) and ls[-1].strip().endswith('}')
        cand = [p for p in rest if os.path.splitext(p)[1].lower() not in ('.h', '.hpp', '.hh') and ends_brace(p)]
        if cand:
            tail = [max(cand, key=lambda p: os.path.getsize(p))]
    rest = [p for p in rest if p not in tail]
    return head + rest + tail


def wrap(line, width):
    if disp_width(line) <= width:
        return [line]
    out, cur, w = [], '', 0
    for ch in line:
        cw = disp_width(ch)
        if w + cw > width:
            out.append(cur); cur, w = '', 0
        cur += ch; w += cw
    if cur:
        out.append(cur)
    return out


def prepare_lines(files, keep_blank, scrub, width):
    lines, flagged, removed, src_map = [], [], [], []
    for p in files:
        text, _ = read_text(p)
        lang = CODE_EXT[os.path.splitext(p)[1].lower()]
        blk = False
        start = len(lines)
        for i, raw in enumerate(text.splitlines(), 1):
            line = raw.expandtabs(4).rstrip().replace('\x0c', '')
            if not line.strip():
                if keep_blank:
                    lines.append('')
                continue
            c, blk2 = is_comment_line(line, lang, blk)
            if SUSPECT.search(line):
                if scrub and c:
                    removed.append('%s:%d: %s' % (p, i, line.strip()[:120]))
                    blk = blk2
                    continue
                flagged.append('%s:%d: %s' % (p, i, line.strip()[:120]))
            blk = blk2
            lines.extend(wrap(line, width))
        src_map.append((p, start + 1, len(lines)))
    return lines, flagged, removed, src_map


